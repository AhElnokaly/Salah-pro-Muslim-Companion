export function getMoonPhaseDetailsForDay(hijriDay: number): MoonPhaseDetails {
  const day = Math.max(1, Math.min(30, hijriDay));
  const isBeed = day >= 13 && day <= 15;
  const fastingDefault = isBeed
    ? 'صيام الأيام البيض مسنون ومؤكد في هذه الليالي المباركة 🌕'
    : 'يستحب الإكثار من النوافل والذكر والدعاء ومراعاة أوقات الإجابة ✨';

  if (day === 1 || day === 30) {
    const desc = 'بداية الشهر القمري وغياب ضوء القمر في المحاق وولادة الهلال الجديد';
    return {
      name: 'محاق (هلال جديد)',
      enName: 'New Moon',
      icon: '🌑',
      illumination: 2,
      age: day,
      description: desc,
      desc,
      fastingNote: fastingDefault,
    };
  }
  if (day >= 2 && day <= 6) {
    const illum = Math.round(((day - 1) / 7) * 45);
    const desc = 'ظهور قوس النور الدقيق وتزايد ضوء القمر تدريجياً في أول الشهر الهجري';
    return {
      name: 'هلال أول الشهر',
      enName: 'Waxing Crescent',
      icon: '🌒',
      illumination: illum,
      age: day,
      description: desc,
      desc,
      fastingNote: fastingDefault,
    };
  }
  if (day === 7 || day === 8) {
    const desc = 'إضاءة نصف وجه القمر المواجه للأرض ووصوله إلى مرحلة التربيع الأول';
    return {
      name: 'تربيع أول',
      enName: 'First Quarter',
      icon: '🌓',
      illumination: 50,
      age: day,
      description: desc,
      desc,
      fastingNote: fastingDefault,
    };
  }
  if (day >= 9 && day <= 12) {
    const illum = 50 + Math.round(((day - 8) / 6) * 45);
    const desc = 'أكثر من نصف وجه القمر مضاء ويتجه نحو الاكتمال والبدر التام';
    return {
      name: 'أحدب متزايد',
      enName: 'Waxing Gibbous',
      icon: '🌔',
      illumination: illum,
      age: day,
      description: desc,
      desc,
      fastingNote: 'اقتراب الأيام البيض المباركة (13 و 14 و 15) فاستعد لصيامها 🌾',
    };
  }
  if (day >= 13 && day <= 15) {
    const desc = 'اكتمال نور البدر في أوج استدارته وتألق الليالي البيض المباركة';
    return {
      name: 'بدر كامل (الليالي البيض)',
      enName: 'Full Moon',
      icon: '🌕',
      illumination: 100,
      age: day,
      description: desc,
      desc,
      fastingNote: '🌕 أيام البيض الآن: يُسن صيامها تأسياً بسنة النبي ﷺ لنيل أجر صيام الدهر',
    };
  }
  if (day >= 16 && day <= 19) {
    const illum = 95 - Math.round(((day - 16) / 6) * 45);
    const desc = 'بدء تناقص الضوء تدريجياً بعد ليلة البدر وانقضاء منتصف الشهر';
    return {
      name: 'أحدب متناقص',
      enName: 'Waning Gibbous',
      icon: '🌖',
      illumination: illum,
      age: day,
      description: desc,
      desc,
      fastingNote: fastingDefault,
    };
  }
  if (day >= 20 && day <= 23) {
    const desc = 'إضاءة النصف الآخر من وجه القمر قبل مرحلة المحاق والدخول في الربع الأخير';
    return {
      name: 'تربيع أخير',
      enName: 'Third Quarter',
      icon: '🌗',
      illumination: 50,
      age: day,
      description: desc,
      desc,
      fastingNote: fastingDefault,
    };
  }
  const illum = Math.max(5, 50 - Math.round(((day - 23) / 7) * 45));
  const desc = 'قوس النور الأخير قبل غياب القمر في المحاق واستقبال هلال الشهر الهجري الجديد';
  return {
    name: 'هلال آخر الشهر',
    enName: 'Waning Crescent',
    icon: '🌘',
    illumination: illum,
    age: day,
    description: desc,
    desc,
    fastingNote: fastingDefault,
  };
}
